import puppeteer from 'puppeteer-core';
const b = await puppeteer.launch({executablePath:'/usr/bin/google-chrome', args:['--no-sandbox']});
const errs=[];
const pg = await b.newPage();
pg.on('pageerror', e=>errs.push(e.message)); pg.on('console', m=>{ if (m.type()==='error') errs.push('console: '+m.text()); });
await pg.setViewport({width:390,height:844, isMobile:true});
const t0=Date.now();
await pg.goto('file:///workspace/interview-prep/index.html', {waitUntil:'networkidle0'});
console.log('load ms', Date.now()-t0, await pg.evaluate(()=>JSON.stringify({t:__QA.total,l:__QA.list})));
await pg.click('button.tab[data-k="p10"]');
await pg.click('#expand'); await new Promise(r=>setTimeout(r,5000));
console.log(await pg.evaluate(()=>({q:document.querySelectorAll('.quick').length, imp:document.querySelectorAll('details.impress').length, code:document.querySelectorAll('.code').length, svg:document.querySelectorAll('.mermaid-box svg').length, boxes:document.querySelectorAll('.mermaid-box').length})));
await pg.evaluate(()=>{ const d=document.querySelector('details.impress'); d.open=true; d.scrollIntoView(); });
await new Promise(r=>setTimeout(r,500));
await pg.screenshot({path:'shot-p10.png'});
await pg.click('button.tab[data-k="list"]');
await pg.evaluate(()=>{ const d=document.querySelector('details[data-lid="131"]'); d.open=true; d.scrollIntoView(); });
await new Promise(r=>setTimeout(r,2500));
console.log('131 ->', await pg.evaluate(()=>document.querySelector('details[data-lid="131"] .ansby').textContent));
await pg.screenshot({path:'shot-131.png'});
console.log('ERRORS', errs);
await b.close();
